def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def hashfile(p: Path):
    return digest(p.read_bytes()) if p.is_file() else None

def target_path(base: Path, name: str) -> Path:
    p = PurePosixPath(name)
    if not name or p.is_absolute() or '\\' in name or any(bit in ('', '.', '..') for bit in p.parts):
        raise ValueError('Unsafe path: ' + name)
    dest = base.joinpath(*p.parts)
    if not dest.resolve().is_relative_to(base.resolve()):
        raise ValueError('Path escapes EMBERA project: '+name)
    cursor = dest
    while cursor != base:
        if cursor.is_symlink():
            raise ValueError('Refusing symlink: '+str(cursor))
        cursor = cursor.parent
    return dest

def main() -> int:
    ap = argparse.ArgumentParser(description='Safely apply EMBERA patch without downloading a ZIP file')
    ap.add_argument('--project', default='.', help='The Hot-Spots repository directory')
    ap.add_argument('--dry-run', action='store_true', help='Check only, make no changes')
    args = ap.parse_args()
    project = Path(args.project).resolve()
    if not (project/'backend'/'zip_api.py').is_file():
        ap.error('Run this inside the EMBERA Hot-Spots project directory')
    raw = base64.b64decode(''.join(BUNDLE_BASE64))
    if digest(raw) != BUNDLE_SHA256:
        raise RuntimeError('Patch payload corrupted; nothing modified')
    stage=[]
    conflicts=[]
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        manifest = json.loads(z.read('manifest.json'))
        for item in manifest['changes']:
            name=item['path']
            dest=target_path(project, name)
            content=z.read('files/'+name)
            if digest(content) != item['after']:
                raise RuntimeError('Damaged payload for '+name)
            current=hashfile(dest)
            if current == item['after']:
                status='ALREADY APPLIED'
            elif current == item['before']:
                status='READY'
                stage.append((item, dest, content))
            else:
                status='CONFLICT'
                conflicts.append(name)
            print(f'{status}: {name}')
    if conflicts:
        print('ABORTED: these files differ from the audited project. Nothing changed.',file=sys.stderr)
        return 2
    if args.dry_run:
        print(f'DRY-RUN SUCCESS: {len(stage)} files ready, no files changed')
        return 0
    if not stage:
        print('Already applied. Nothing changed.')
        return 0
    stamp=datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    backup=project.parent/('EMBERA_PATCH_BACKUP_'+stamp)
    backup.mkdir(exist_ok=False)
    changed=[]
    try:
        for item,dest,_ in stage:
            if item['before'] is not None:
                saved=backup/item['path']
                saved.parent.mkdir(parents=True,exist_ok=True)
                shutil.copy2(dest,saved)
        for item,dest,content in stage:
            dest.parent.mkdir(parents=True,exist_ok=True)
            fd,tmp=tempfile.mkstemp(prefix='.embera-patch-', dir=dest.parent)
            try:
                with os.fdopen(fd,'wb') as stream:
                    stream.write(content)
                    stream.flush()
                    os.fsync(stream.fileno())
                os.replace(tmp,dest)
            finally:
                if os.path.exists(tmp): os.unlink(tmp)
            changed.append((item,dest))
        (backup/'PATCH_SUMMARY.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    except Exception:
        for item,dest in reversed(changed):
            if item['before'] is None:
                dest.unlink(missing_ok=True)
            else:
                shutil.copy2(backup/item['path'],dest)
        print('Patch failed and was rolled back. Backup:',backup,file=sys.stderr)
        raise
    print(f'SUCCESS: applied {len(changed)} files; backup at {backup}')
    print(r'Next: git diff --check ; .\.venv\Scripts\python.exe -m pytest -q ; npm.cmd run build')
    return 0

if __name__ == '__main__':
    sys.exit(main())
